# TN9K: SD SPI MMIO CMD0 via shim @ 0xFFFF3000; UART "OK\r\n" on success.
# r23 = UART 0xFFFF1000, r25 = SD 0xFFFF3000, r16 = mask, r17 = 1 (busy bit).

MOV 21 -1
MOV 22 16
SLL 21 22 21
ADDI 21 23 4096
ADDI 21 25 12288

MOV 16 2
MOV 17 1

MOV 10 1
STR 25 10 15 0
MOV 10 0
STR 25 11 15 12
MOV 10 256
STR 25 10 15 8

wt_sd:
LDR 25 20 15 20
ANDS 20 17 0
JNZ wt_sd

MOV 11 79
STR 23 11 1 0
MOV 11 75
STR 23 11 1 0
MOV 12 13
STR 23 12 1 0
MOV 12 10
STR 23 12 1 0

wt_uart:
LDR 23 20 15 8
ANDS 20 16 0
JZ wt_uart

idle:
NOP
B idle
